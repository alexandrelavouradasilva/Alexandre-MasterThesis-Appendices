"""
Testing NN Model and Plot

This script automates the visual evaluation of the machine learning model by 
generating detailed, publication-ready parity plots. It reconstructs the exact 
train-validation-test data splits and imports the corresponding true and predicted 
values generated by the Artificial Neural Network. For each of the 9 target 
parameters, the script dynamically calculates individual R-squared metrics and 
overlays the predictions on a single set of axes, using gradient coloring to 
clearly distinguish between training, validation, and test datasets. Finally, 
it exports the final grid of scatter plots in both high-resolution PNG and 
scalable vector PDF formats.
"""

import numpy as np
import pandas as pd
import os
import matplotlib.pyplot as plt
from sklearn.metrics import r2_score
from sklearn.model_selection import train_test_split

# ==========================================
# 1. PATHS AND CONFIGURATIONS
# ==========================================
BASE_DIR = r"C:\Users\alexandre.lavoura\Desktop\teseMestradoAlexandre\teseMestradoAlexandre\mlpcp-interp-main"
DATA = os.path.join(BASE_DIR, "data", "data_cpb")
PLOTS_DIR = os.path.join(BASE_DIR, "plots") 

# Test Files
Y_TEST_FILE = os.path.join(DATA, "y_test.csv")
PRED_TEST_FILE = os.path.join(DATA, "y_pred_nn.csv")

# Original Training Files and Predictions (Train + Validation)
Y_TRAIN_FULL_FILE = os.path.join(DATA, "y_train.csv")
PRED_TRAIN_FILE = os.path.join(DATA, "y_pred_train_nn.csv")
PRED_VAL_FILE = os.path.join(DATA, "y_pred_val_nn.csv")

if not os.path.exists(PLOTS_DIR):
    os.makedirs(PLOTS_DIR)

# ==========================================
# 2. LOAD AND SPLIT DATA
# ==========================================
print("Loading True and Predicted values for Train, Validation, and Test sets...")

# Read true values and reconstruct the exact training split
y_test_df = pd.read_csv(Y_TEST_FILE)
y_train_full_df = pd.read_csv(Y_TRAIN_FULL_FILE)
y_train_df, y_val_df = train_test_split(y_train_full_df, test_size=999, random_state=42)

# Read predictions
y_pred_test_df = pd.read_csv(PRED_TEST_FILE)
y_pred_train_df = pd.read_csv(PRED_TRAIN_FILE)
y_pred_val_df = pd.read_csv(PRED_VAL_FILE)

selected = ['C12', 'C13', 'C22', 'C23', 'C33', 'C66', 'sigma0', 'k', 'n']

labels_map = {
    'C12': r'$C_{12}$', 'C13': r'$C_{13}$', 'C22': r'$C_{22}$',
    'C23': r'$C_{23}$', 'C33': r'$C_{33}$', 'C66': r'$C_{66}$',
    'sigma0': r'$Y_0$', 'k': r'$K$', 'n': r'$n$'
}

# Convert DataFrames to Numpy Arrays
y_test_true = y_test_df[selected].values
y_test_pred = y_pred_test_df[selected].values

y_train_true = y_train_df[selected].values
y_train_pred = y_pred_train_df[selected].values

y_val_true = y_val_df[selected].values
y_val_pred = y_pred_val_df[selected].values

# ==========================================
# 3. PLOT GENERATION (LaTeX Configuration)
# ==========================================
print("\nGenerating final correlation parity plot for the Neural Network...")

plt.rcParams.update({
    "font.family": "serif",  
    "font.serif": ["Times New Roman"],
    "text.usetex": True
})

with plt.rc_context({'font.size': 13}):
    fig, axes = plt.subplots(3, 3, figsize=(18, 21))

    for ax, name in zip(axes.flat, selected):
        i = selected.index(name)

        # Isolate columns for current parameter
        true_train = y_train_true[:, i]
        pred_train = y_train_pred[:, i]
        
        true_val = y_val_true[:, i]
        pred_val = y_val_pred[:, i]

        true_test = y_test_true[:, i]
        pred_test = y_test_pred[:, i]

        # DYNAMIC R-SQUARED CALCULATION
        r2_train_i = r2_score(true_train, pred_train)
        r2_val_i = r2_score(true_val, pred_val)
        r2_test_i = r2_score(true_test, pred_test)

        # ---------------------------------------------------------
        # SCATTER PLOTS: TRAIN -> VALIDATION -> TEST
        # ---------------------------------------------------------
        ax.scatter(true_train, pred_train, alpha=0.3, s=8,  color='#d3d3d3', label='Train', zorder=1)
        ax.scatter(true_val,   pred_val,   alpha=0.5, s=8,  color='#808080', label='Validation', zorder=2)
        ax.scatter(true_test,  pred_test,  alpha=0.7, s=15, color='black',   label='Test', zorder=3)
        
        # Calculate dynamic axis limits based on the min/max of ALL data points
        all_vals = np.concatenate([true_train, pred_train, true_val, pred_val, true_test, pred_test])
        lo, hi = all_vals.min(), all_vals.max()
        margem = (hi - lo) * 0.05
        lo, hi = lo - margem, hi + margem
        
        # Identity line (perfect prediction)
        ax.plot([lo, hi], [lo, hi], '--', color='black', linewidth=1.5, zorder=4)

        # Parameter label (LaTeX formatted)
        ax.text(0.05, 0.95, labels_map.get(name, name),
                transform=ax.transAxes,
                fontsize=32, fontweight='bold',
                verticalalignment='top', horizontalalignment='left')

        # Subplot title accommodating the three R-squared values
        ax.set_title(
            f'$R^2$: train={r2_train_i:.2f} $|$ val={r2_val_i:.2f} $|$ test={r2_test_i:.2f}',
            fontsize=20, pad=10
        )
        
        # Axis configuration
        ax.set_xlabel('True', fontsize=25)
        ax.set_ylabel('Predicted', fontsize=25)
        ax.tick_params(axis='both', which='major', labelsize=20)
        ax.locator_params(axis='x', nbins=4)
        ax.locator_params(axis='y', nbins=4)
        
        # Ensure square limits and aspect ratio
        ax.set_xlim(lo, hi)
        ax.set_ylim(lo, hi)
        ax.set_aspect('equal', adjustable='box')
        ax.patch.set_alpha(0)

    # Global legend with 3 columns
    handles, legend_labels = axes.flat[0].get_legend_handles_labels()
    fig.legend(handles, legend_labels, loc='lower center', ncol=3,
               bbox_to_anchor=(0.5, -0.015), fontsize=25,
               framealpha=0, frameon=True)
    
    plt.tight_layout()
    
    save_path_png = os.path.join(PLOTS_DIR, 'parity_plots_NN_latex.png')
    save_path_pdf = os.path.join(PLOTS_DIR, 'parity_plots_NN_latex.pdf')
    
    plt.savefig(save_path_png, dpi=300, bbox_inches='tight', transparent=True)
    plt.savefig(save_path_pdf, dpi=300, bbox_inches='tight', transparent=True)
    
    print(f"✅ Plots successfully saved to:\n - {save_path_png}\n - {save_path_pdf}")
